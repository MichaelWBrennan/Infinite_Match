/**
 * Friend invitation system.
 *
 * Players can generate invite codes to share with friends. When a new player
 * joins using an invite code, both the inviter and the invitee receive rewards.
 * Invites are tracked server-side with rewards granted once the invitee reaches
 * certain milestones (e.g., completes their first level).
 *
 * Rewards:
 *   - Invitee: starter coins boost on first level win
 *   - Inviter: coins when invitee completes first level
 */

import { Logger } from '../../../core/logger/index.js';
import crypto from 'crypto';

const logger = new Logger('FriendInvites');

const INVITE_CODE_LENGTH = 8;
const INVITE_EXPIRY_DAYS = 30;
const INVITEE_REWARD_COINS = 500;
const INVITER_REWARD_COINS = 250;

/**
 * Invite code alphabet (no ambiguous characters like 0/O, 1/l, I).
 */
const CODE_ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';

function generateInviteCode() {
  let code = '';
  for (let i = 0; i < INVITE_CODE_LENGTH; i++) {
    code += CODE_ALPHABET[crypto.randomInt(CODE_ALPHABET.length)];
  }
  return code;
}

/**
 * Friend invitation state (in-memory).
 *
 * invites: Map<code, { code, inviterId, createdAt, expiresAt, usedBy, usedAt }>
 * playerInvites: Map<playerId, Set<code>> - invites generated by a player
 * playerInvitedBy: Map<playerId, code> - which code a player used to join
 * inviteMilestones: Map<code, Set<string>> - milestones reached by invitee
 */
const invites = new Map();
const playerInvites = new Map();
const playerInvitedBy = new Map();
const inviteMilestones = new Map();

/**
 * Generates a new invite code for a player.
 * Returns { code, inviteUrl, expiresAt }.
 */
export function generateInvite(inviterId, nowMs = Date.now()) {
  let code;
  let attempts = 0;
  do {
    code = generateInviteCode();
    attempts++;
    if (attempts > 100) throw new Error('invite_code_generation_failed');
  } while (invites.has(code));

  const expiresAt = nowMs + INVITE_EXPIRY_DAYS * 24 * 60 * 60 * 1000;
  const invite = {
    code,
    inviterId,
    createdAt: nowMs,
    expiresAt,
    usedBy: null,
    usedAt: null,
  };
  invites.set(code, invite);

  let playerCodes = playerInvites.get(inviterId);
  if (!playerCodes) {
    playerCodes = new Set();
    playerInvites.set(inviterId, playerCodes);
  }
  playerCodes.add(code);

  logger.info('Invite code generated', { inviterId, code, expiresAt });

  return {
    code,
    inviteUrl: `https://game.example/invite/${code}`,
    expiresAt,
  };
}

/**
 * Validates an invite code. Returns { valid, invite } or { valid: false, reason }.
 */
export function validateInviteCode(code, nowMs = Date.now()) {
  const invite = invites.get(code);
  if (!invite) {
    return { valid: false, reason: 'invite_not_found' };
  }
  if (invite.usedBy) {
    return { valid: false, reason: 'invite_already_used' };
  }
  if (nowMs > invite.expiresAt) {
    return { valid: false, reason: 'invite_expired' };
  }
  return { valid: true, invite };
}

/**
 * Records that a player joined using an invite code.
 * Returns { success, inviterId } or { success: false, reason }.
 */
export function useInviteCode(code, inviteeId, nowMs = Date.now()) {
  const validation = validateInviteCode(code, nowMs);
  if (!validation.valid) {
    return { success: false, reason: validation.reason };
  }

  const invite = validation.invite;
  if (invite.inviterId === inviteeId) {
    return { success: false, reason: 'self_invite' };
  }

  // Check if this player was already invited by someone
  if (playerInvitedBy.has(inviteeId)) {
    return { success: false, reason: 'already_invited' };
  }

  invite.usedBy = inviteeId;
  invite.usedAt = nowMs;

  playerInvitedBy.set(inviteeId, code);

  logger.info('Invite code used', { code, inviterId: invite.inviterId, inviteeId });

  return {
    success: true,
    inviterId: invite.inviterId,
    code,
  };
}

/**
 * Returns the invite code a player used to join, or null.
 */
export function getInvitedBy(playerId) {
  return playerInvitedBy.get(playerId) || null;
}

/**
 * Returns all invites generated by a player.
 */
export function getPlayerInvites(playerId) {
  const codes = playerInvites.get(playerId);
  if (!codes) return [];
  return Array.from(codes).map((code) => ({
    ...invites.get(code),
    claimed: false, // Would check milestone claims
  }));
}

/**
 * Records that an invitee reached a milestone (e.g., first level win).
 * Returns { success, inviterReward, inviteeReward } or { success: false, reason }.
 */
export function reachMilestone(code, milestone, nowMs = Date.now()) {
  const invite = invites.get(code);
  if (!invite) {
    return { success: false, reason: 'invite_not_found' };
  }
  if (!invite.usedBy) {
    return { success: false, reason: 'invite_not_used' };
  }

  const milestones = inviteMilestones.get(code) || new Set();
  if (milestones.has(milestone)) {
    return { success: false, reason: 'milestone_already_reached' };
  }

  if (!inviteMilestones.has(code)) {
    inviteMilestones.set(code, new Set());
  }
  inviteMilestones.get(code).add(milestone);

  const rewards = {};
  if (milestone === 'first_level_win') {
    rewards.inviterReward = { coins: INVITER_REWARD_COINS };
    rewards.inviteeReward = { coins: INVITEE_REWARD_COINS };
  }

  logger.info('Invite milestone reached', { code, milestone, inviterId: invite.inviterId, inviteeId: invite.usedBy });

  return {
    success: true,
    milestone,
    inviterId: invite.inviterId,
    inviteeId: invite.usedBy,
    ...rewards,
  };
}

/**
 * Resets all in-memory invite state (for testing only).
 */
export function resetForTesting() {
  invites.clear();
  playerInvites.clear();
  playerInvitedBy.clear();
  inviteMilestones.clear();
}

/**
 * Returns invite statistics for a player (how many invites, how many used, etc.).
 */
export function getInviteStats(playerId) {
  const codes = playerInvites.get(playerId);
  if (!codes) {
    return { total: 0, used: 0, pending: 0, expired: 0 };
  }

  let used = 0;
  let pending = 0;
  let expired = 0;
  const nowMs = Date.now();

  for (const code of codes) {
    const invite = invites.get(code);
    if (!invite) continue;
    if (invite.usedBy) used++;
    else if (nowMs > invite.expiresAt) expired++;
    else pending++;
  }

  return { total: codes.size, used, pending, expired };
}

export default {
  generateInvite,
  validateInviteCode,
  useInviteCode,
  getInvitedBy,
  getPlayerInvites,
  reachMilestone,
  getInviteStats,
};
