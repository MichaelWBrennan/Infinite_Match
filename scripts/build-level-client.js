#!/usr/bin/env node
// Build the classic-script browser adapter from the EXACT pure server generator.
// No separate browser algorithm, bundler dependency or hand-maintained copy.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = readFileSync(new URL('../src/services/levels/generator.js', import.meta.url), 'utf8');
const environment = readFileSync(new URL('../src/services/levels/environment.js', import.meta.url), 'utf8');
const names = [...(environment + '\n' + source).matchAll(/^export (?:const|function) (\w+)/gm)].map((match) => match[1]);
const regions = readFileSync(new URL('../src/services/levels/time-zone-regions.js', import.meta.url), 'utf8').replace(/^export /gm, '');
const body = regions + '\n' + environment.replace(/^export /gm, '') + '\n'
  + source.replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const result = `// Generated by scripts/build-level-client.js. Do not edit; edit src/services/levels/generator.js.\n(function (root) {\n'use strict';\n${body}\nroot.InfiniteLevels = Object.freeze({ TIME_ZONE_REGIONS, ${names.join(', ')} });\n})(globalThis);\n`;
const target = new URL('../public/js/procedural-levels.js', import.meta.url);
mkdirSync(fileURLToPath(new URL('../public/js/', import.meta.url)), { recursive: true });
writeFileSync(target, result);

// Keep the actual upstream license and Wikipedia attributions in self-hosted builds.
mkdirSync(new URL('../public/licenses/', import.meta.url), { recursive: true });
copyFileSync(new URL('../node_modules/date-holidays/LICENSE', import.meta.url),
  new URL('../public/licenses/date-holidays.txt', import.meta.url));
