#!/usr/bin/env node
// Build the classic-script browser adapter from the EXACT pure server generator.
// No separate browser algorithm, bundler dependency or hand-maintained copy.
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const modules = ['time-zone-regions.js', 'environment.js', 'match-core.js', 'special-rules.js', 'shield-rules.js', '../meta/rewards.js', 'objective-rules.js', 'generator.js'];
const sources = modules.map((name) => readFileSync(new URL(`../src/services/levels/${name}`, import.meta.url), 'utf8'));
const names = [...new Set(sources.flatMap((source) => [...source.matchAll(/^export (?:const|function) (\w+)/gm)].map((match) => match[1])))];
const body = sources.map((source) => source.replace(/^import .*;\n/gm, '')
  .replace(/^export \{.*\} from .*;\n/gm, '').replace(/^export /gm, '')).join('\n');
const result = `// Generated by scripts/build-level-client.js. Do not edit; edit the pure modules in src/services/levels/.\n(function (root) {\n'use strict';\n${body}\nroot.InfiniteLevels = Object.freeze({ ${names.join(', ')} });\n})(globalThis);\n`;
const target = new URL('../public/js/procedural-levels.js', import.meta.url);
mkdirSync(fileURLToPath(new URL('../public/js/', import.meta.url)), { recursive: true });
writeFileSync(target, result);

// Keep the actual upstream license and Wikipedia attributions in self-hosted builds.
mkdirSync(new URL('../public/licenses/', import.meta.url), { recursive: true });
copyFileSync(new URL('../node_modules/date-holidays/LICENSE', import.meta.url),
  new URL('../public/licenses/date-holidays.txt', import.meta.url));
