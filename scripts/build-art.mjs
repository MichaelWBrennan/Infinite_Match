#!/usr/bin/env node
/**
 * Export the canonical Infinite Match artwork from the same vector renderer the
 * browser uses. Run `npm run art:build` after changing palette or art direction.
 * `npm run art:check` verifies committed PNGs/manifests are reproducible.
 */
import { createCanvas } from '@napi-rs/canvas';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');
const sandbox = { console };
vm.createContext(sandbox);
vm.runInContext(read('public/js/procedural-levels.js'), sandbox, { filename: 'procedural-levels.js' });
vm.runInContext(read('public/js/art-direction.js'), sandbox, { filename: 'art-direction.js' });
const art = sandbox.InfiniteArt;
if (!art) throw new Error('InfiniteArt failed to load');

const files = new Map();
function raster(size, draw, logical = true) {
  const canvas = createCanvas(size, size);
  const context = canvas.getContext('2d');
  if (logical) context.scale(size / art.SIZE, size / art.SIZE);
  draw(context);
  return canvas.toBuffer('image/png');
}
function put(rel, buffer) { files.set(rel, buffer); }

const themes = art.themeCatalog();
const manifest = {
  version: 2,
  artDirection: art.VERSION,
  description: 'Canonical runtime artwork for Infinite Match. Generated by scripts/build-art.mjs from public/js/art-direction.js; do not edit PNGs by hand.',
  basePath: 'public/art',
  gemCount: art.SLOT_SHAPES.length,
  license: 'MIT',
  attribution: 'Infinite Match contributors',
  themes: {},
  boosters: {},
  uiIcons: {},
  terrain: {},
  shields: {},
  icons: {},
  referenceLibraries: [
    { path: 'assets/match3/', status: 'reference-only', note: 'Legacy downloaded/source candidate tiles. Not loaded by the playable web runtime; verify provenance before any reuse.' },
    { path: 'assets_external/', status: 'reference-only', note: 'External source candidates. Not loaded by the playable web runtime.' },
  ],
};

for (const theme of themes) {
  const entry = { name: theme.name, background: theme.background, accent: theme.accent, gems: [] };
  for (const gem of theme.gems) {
    const rel = `gems/${theme.id}/${gem.id}.png`;
    put(`public/art/${rel}`, raster(128, (ctx) => art.drawGem(ctx, gem.id, null, { [gem.id]: gem })));
    entry.gems.push({ id: gem.id, shape: gem.shape, symbol: gem.symbol, color: gem.color, file: rel });
  }
  manifest.themes[theme.id] = entry;
}
for (const type of art.boosterTypes) {
  const rel = `ui/boosters/${type}.png`;
  put(`public/art/${rel}`, raster(128, (ctx) => art.drawBooster(ctx, type)));
  manifest.boosters[type] = rel;
}
for (const name of art.uiIcons) {
  const rel = `ui/icons/${name}.png`;
  const buffer = raster(128, (ctx) => art.drawUiIcon(ctx, name));
  put(`public/art/${rel}`, buffer);
  put(`assets/ui/icons/${name}.png`, buffer);
  put(`unity/Assets/Resources/UI/Icons/${name}.png`, buffer);
  put(`unity-refactored/Assets/Resources/UI/Icons/${name}.png`, buffer);
  manifest.uiIcons[name] = rel;
}
for (const kind of art.terrainTypes) {
  manifest.terrain[kind] = {};
  for (const layers of [1, 2, 3]) {
    const rel = `ui/terrain/${kind}_${layers}.png`;
    put(`public/art/${rel}`, raster(128, (ctx) => art.drawTerrain(ctx, kind, layers)));
    manifest.terrain[kind][layers] = rel;
  }
}
for (const layers of [1, 2]) {
  const rel = `ui/shield_${layers}.png`;
  put(`public/art/${rel}`, raster(128, (ctx) => art.drawShield(ctx, layers)));
  manifest.shields[layers] = rel;
}

const iconSpecs = [
  ['public/icons/icon-192.png', 192, false, 'any'],
  ['public/icons/icon-512.png', 512, false, 'any'],
  ['public/icons/icon-maskable-512.png', 512, true, 'maskable'],
  ['public/icons/apple-touch-icon.png', 180, true, 'apple'],
  ['assets/ui/icon.png', 512, false, 'source'],
];
for (const [rel, size, maskable, purpose] of iconSpecs) {
  put(rel, raster(size, (ctx) => art.drawBrand(ctx, size, { maskable }), false));
  // App icons live in public/icons, one level above the public/art atlas root.
  if (rel.startsWith('public/icons/')) manifest.icons[purpose] = { file: `../icons/${path.basename(rel)}`, size, purpose };
}

const manifestText = JSON.stringify(manifest, null, 2) + '\n';
put('assets/manifest.json', Buffer.from(manifestText));
put('public/art/manifest.json', Buffer.from(JSON.stringify({ ...manifest, basePath: '.' }, null, 2) + '\n'));

let changed = 0;
for (const [rel, buffer] of files) {
  const target = path.join(root, rel);
  if (check) {
    const existing = fs.existsSync(target) ? fs.readFileSync(target) : null;
    if (!existing || !existing.equals(buffer)) {
      console.error(`Art asset is missing or stale: ${rel}`);
      changed++;
    }
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, buffer);
  }
}
if (check) {
  if (changed) {
    console.error(`${changed} art asset(s) need regeneration. Run npm run art:build.`);
    process.exit(1);
  }
  console.log(`Art check passed: ${files.size} canonical assets are up to date.`);
} else {
  console.log(`Wrote ${files.size} canonical art assets (${themes.length} themes, ${art.boosterTypes.length} boosters, ${art.terrainTypes.length} terrain families).`);
}
